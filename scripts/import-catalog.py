"""Import the bundled PokeFinder 3.4 assets and reference text."""
import json
import re
import shutil
import struct
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
old = Path(sys.argv[1]).resolve() / 'app/src/main'
assets = root / 'assets'
data = root / 'src/data'
data.mkdir(parents=True, exist_ok=True)
for name in ('catalog.json', 'legacy_codes.json', 'reference.json'):
    shutil.copyfile(old / 'assets' / name, data / name)

art = assets / 'sprites'
art.mkdir(exist_ok=True)
for image in (old / 'res/drawable-nodpi').glob('*.png'):
    shutil.copyfile(image, art / image.name)
shutil.copyfile(art / 'brand_icon.png', assets / 'app-icon.png')
shutil.copytree(old / 'assets/dex-gifs', assets / 'dex-gifs', dirs_exist_ok=True)
gif_paths = sorted((assets / 'dex-gifs').glob('*/*.gif'))
dimensions = {}
for path in gif_paths:
    with path.open('rb') as gif:
        dimensions[f'{path.parent.name}/{path.stem}'] = struct.unpack_from('<HH', gif.read(10), 6)
(data / 'gif-sizes.json').write_text(json.dumps(dimensions, separators=(',', ':')) + '\n', encoding='utf-8')
with (data / 'images.ts').open('w', encoding='utf-8') as manifest:
    manifest.write("// Generated by scripts/import-catalog.py.\n")
    for name, paths in [('sprites', sorted(art.glob('*.png'))),
                        ('animations', gif_paths)]:
        manifest.write(f'export const {name}: Record<string, number> = {{\n')
        for path in paths:
            key = path.stem if name == 'sprites' else f'{path.parent.name}/{path.stem}'
            relative = path.relative_to(root).as_posix()
            manifest.write(f"  '{key}': require('../../{relative}'),\n")
        manifest.write('};\n')

kotlin = old / 'java/app/pokecode/finder'
quoted = r'"(?:[^"\\]|\\.)*"'
string = r'(' + quoted + r')'
help_source = (kotlin / 'Help.kt').read_text(encoding='utf-8')
intro = [[json.loads(x) for x in row] for row in
         re.findall(r'HelpTopic\(' + string + ', ' + string + r'\)', help_source)]
help_panels = []
for title, body in re.findall(r'HelpPanel\(' + string + r'\) \{(.*?)\n            \}', help_source, re.S):
    paragraphs = []
    link = None
    steps = re.search(r'Steps\((.*?)\n\s*\)', body, re.S)
    paragraph = re.search(r'Text\(' + string + r'\)', body)
    source = re.search(r'SourceButton\(' + string + ', ' + string + r'\)', body)
    if steps:
        paragraphs = [f'{i}. {json.loads(s)}'
                      for i, s in enumerate(re.findall(quoted, steps[1]), 1)]
    if paragraph:
        paragraphs.append(json.loads(paragraph[1]))
    if source:
        link = [json.loads(x) for x in source.groups()]
    help_panels.append({'title': json.loads(title), 'paragraphs': paragraphs, 'link': link})
credits_source = (kotlin / 'Credits.kt').read_text(encoding='utf-8')
credits = {}
for name, body in re.findall(r'private val (\w+) = listOf\((.*?)\n\)', credits_source, re.S):
    credits[name] = [[json.loads(title), json.loads(url) if url else ''] for title, url in
                     re.findall(r'CreditSource\(' + string + r'(?:,\s*' + string + r')?\)', body)]
assert len(intro) == 4 and len(help_panels) == 6 and len(credits) == 3
(data / 'help.json').write_text(json.dumps({'intro': intro, 'panels': help_panels, 'credits': credits},
                                          ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
