"""Build small local tiles from the Yellow checklist archive."""
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile
import sys
from PIL import Image

root = Path(__file__).resolve().parents[1]
output = root / 'assets/map-yellow'
output.mkdir(parents=True, exist_ok=True)
bounds = {
    'pallet': (1496, 4256, 1856, 4576),
    'route1': (1528, 3664, 1832, 4264),
    'celadon': (3088, 2256, 3968, 2824),
}
rows = ["// Generated by scripts/prepare-yellow-map.py.",
        "type Tile = { x: number; y: number; width: number; height: number; image: number };",
        "export const yellowTiles: Record<string, { width: number; height: number; low: Tile[]; high: Tile[] }> = {"]
with ZipFile(sys.argv[1]) as archive:
    member = next(name for name in archive.namelist() if name.endswith('/full.png'))
    with Image.open(BytesIO(archive.read(member))) as source:
        if source.size != (8192, 8192):
            raise ValueError('Unexpected map dimensions')
        for area, (left, top, right, bottom) in bounds.items():
            image = source.crop((left, top, right, bottom)).convert('RGBA')
            width, height = image.size
            rows.append(f"  {area}: {{ width: {width}, height: {height},")
            for level, downsample, span in [('low', 2, 512), ('high', 1, 256)]:
                rows.append(f'    {level}: [')
                for y in range(0, height, span):
                    for x in range(0, width, span):
                        w, h = min(span, width - x), min(span, height - y)
                        tile = image.crop((x, y, x + w, y + h))
                        if downsample > 1:
                            tile = tile.resize((w // downsample, h // downsample), Image.Resampling.NEAREST)
                        name = f'{area}_{level}_{x}_{y}.png'
                        tile.save(output / name, optimize=True)
                        rows.append(f"      {{ x: {x}, y: {y}, width: {w}, height: {h}, image: require('../../assets/map-yellow/{name}') }},")
                rows.append('    ],')
            rows.append('  },')
rows.append('};')
(root / 'src/data/yellow-map-tiles.ts').write_text('\n'.join(rows) + '\n', encoding='utf-8')
